#!/usr/bin/env node
/** Generate the committed source/export manifest and consumer hashes. */
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const CONSUMERS = process.env.G5A_CONSUMERS ?? path.resolve(ROOT, "../g5a-consumers");
const OUT_JSON = path.join(ROOT, "docs/g5a/G5A_MANIFEST.json");
const OUT_MD = path.join(ROOT, "docs/G5A_MANIFEST.md");
const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");

const files = [];
async function walk(relative) {
  const absolute = path.join(ROOT, relative);
  let info;
  try { info = await stat(absolute); } catch { return; }
  if (info.isFile()) {
    if (absolute === OUT_JSON || absolute === OUT_MD) return;
    const bytes = await readFile(absolute);
    files.push({ path: relative.replaceAll("\\", "/"), bytes: bytes.length, sha256: sha256(bytes) });
    return;
  }
  const entries = await readdir(absolute, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
    await walk(path.join(relative, entry.name));
  }
}

for (const target of [
  "app/living-type",
  "components/living-type-demo",
  "docs/assets/g5a",
  "docs/G3A1_REPORT.md",
  "docs/G5A_BROWSER_MATRIX.md",
  "docs/G5A_GATE0_SOURCE.md",
  "docs/G5A_PERFORMANCE.md",
  "docs/G5A_ROLLBACK.md",
  "docs/G5A_SECURITY.md",
  "docs/g5a",
  "G5A_REPORT.md",
  "package.json",
  "pnpm-lock.yaml",
  "public/r/living-type-01.json",
  "README.md",
  "registry.json",
  "registry.g5a.json",
  "registry/nullworx/living-type-01",
  "scripts/g3a1",
  "scripts/g5a",
  "scripts/living-type-contract.ts",
  "scripts/registry.mjs",
  "scripts/verify-composition.mjs",
  "third_party/unbounded",
  "THIRD_PARTY_NOTICES.md",
]) {
  await walk(target);
}

const consumers = {};
for (const name of ["next", "vite"]) {
  const root = path.join(CONSUMERS, name);
  const installedRoot = name === "next" ? "components/living-type-01" : "src/components/living-type-01";
  const installed = [];
  for (const entry of (await readdir(path.join(root, installedRoot))).sort()) {
    const bytes = await readFile(path.join(root, installedRoot, entry));
    installed.push({ path: `${installedRoot}/${entry}`, bytes: bytes.length, sha256: sha256(bytes) });
  }
  const packageJson = await readFile(path.join(root, "package.json"));
  const lock = await readFile(path.join(root, "package-lock.json"));
  consumers[name] = {
    root,
    packageJsonSha256: sha256(packageJson),
    packageLockSha256: sha256(lock),
    installed,
  };
}

const sourceBytes = files.reduce((sum, file) => sum + file.bytes, 0);
const manifest = {
  generatedAt: new Date().toISOString(),
  branch: "feat/g5a-living-type-01",
  baseHead: "e5e4119e791e7815b8b6e8efe4439b123fc61225",
  source: files,
  sourceBytes,
  consumers,
  font: {
    sourceWoff2: "third_party/unbounded/unbounded-latin-wght-normal.woff2",
    sourceSha256: "22f9b928aa3928a896340422b54d690fbb5875c30eae4c106f029c61f2289fd6",
    subsetWoff2: "third_party/unbounded/unbounded-living-type-ascii.woff2",
    subsetSha256: "3e99d2422c4a5c962cbd13889295e0d7d5273c844aeff1a2b35f9c54c4721d2b",
    license: "SIL Open Font License 1.1",
  },
  product: {
    item: "living-type-01",
    itemFile: "public/r/living-type-01.json",
    runtimeDependencies: ["@paper-design/shaders-react@0.0.82"],
    sourceParity: { next: "12/12", vite: "12/12" },
  },
};
await writeFile(OUT_JSON, JSON.stringify(manifest, null, 2) + "\n");

const rows = files.map((file) => `| \`${file.path}\` | ${file.bytes} | \`${file.sha256}\` |`).join("\n");
const installedRows = Object.entries(consumers).map(([name, value]) => {
  return `| ${name} | ${value.installed.length} | ${value.installed.reduce((sum, file) => sum + file.bytes, 0)} | \`${value.packageJsonSha256.slice(0, 16)}…\` |`;
}).join("\n");
const markdown = `# G5-A exact source/export manifest

Generated by \`scripts/g5a/build-manifest.mjs\` from branch
\`feat/g5a-living-type-01\` at base \`e5e4119e791e7815b8b6e8efe4439b123fc61225\`.
The machine-readable version is [docs/g5a/G5A_MANIFEST.json](g5a/G5A_MANIFEST.json).

- Source files listed: **${files.length}**
- Source bytes: **${sourceBytes}**
- Runtime dependency: \`@paper-design/shaders-react@0.0.82\`
- Install source parity: Next **12/12**, Vite **12/12**
- Font source SHA-256: \`22f9b928…f2289fd6\`
- Embedded subset SHA-256: \`3e99d242…4721d2b\`

## Installable export

| Consumer | Files | Bytes | package.json hash prefix |
| --- | ---: | ---: | --- |
${installedRows}

## Source files

| Path | Bytes | SHA-256 |
| --- | ---: | --- |
${rows}

The full consumer file hashes and package-lock hashes are in the JSON manifest.
Evidence under \`evidence/g5a/\` is local and gitignored; committed summaries are
under \`docs/g5a/evidence/\`. The G3-A.1 source/evidence preservation archive is
intentionally outside Git.
`;
await writeFile(OUT_MD, markdown);
console.log(JSON.stringify({ files: files.length, sourceBytes, consumers: Object.keys(consumers), json: OUT_JSON, markdown: OUT_MD }, null, 2));
